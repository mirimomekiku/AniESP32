#!/usr/bin/env python3
"""Render open-license pixel fonts (tools/fonts, SIL OFL) to 1-bit bitmap tables in src/font_data.*"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = [
    ("SILK", "Silkscreen-Bold.ttf", 8),     # labels: compact caps
    ("CHUNK", "PressStart2P-Regular.ttf", 8),  # numbers and headings: chunky 8x8
]
FIRST, LAST = 32, 126


def render(path, size):
    f = ImageFont.truetype(path, size)
    glyphs, adv = {}, {}
    top, bottom = 99, -1
    for code in range(FIRST, LAST + 1):
        c = chr(code)
        img = Image.new("L", (16, 20), 255)
        d = ImageDraw.Draw(img)
        d.fontmode = "1"
        d.text((0, 0), c, font=f, fill=0)
        px = img.load()
        rows = [[px[x, y] == 0 for x in range(16)] for y in range(20)]
        glyphs[code] = rows
        adv[code] = max(1, int(round(f.getlength(c))))
        for y, r in enumerate(rows):
            if any(r):
                top, bottom = min(top, y), max(bottom, y)
    return glyphs, adv, top, bottom


def main():
    h_out = ["// Generated by tools/make_font.py - do not edit", "#pragma once", "#include <Arduino.h>", "",
             "struct PixelFont {", "  const uint8_t *bits;  // 95 glyphs x h rows, one byte per row, MSB = leftmost pixel", "  const uint8_t *adv;   // advance width per glyph", "  uint8_t h;", "  uint8_t capTop, capH;  // rows of a capital letter (for vertical centring)", "};", ""]
    c_out = ["// Generated by tools/make_font.py - do not edit", '#include "font_data.h"', ""]
    for name, ttf, size in FONTS:
        glyphs, adv, top, bottom = render(os.path.join(ROOT, "tools", "fonts", ttf), size)
        h = bottom - top + 1
        data = []
        for code in range(FIRST, LAST + 1):
            for y in range(top, top + h):
                row = glyphs[code][y][:8]
                b = 0
                for x, on in enumerate(row):
                    if on:
                        b |= 0x80 >> x
                data.append(b)
        c_out.append(f"static const uint8_t {name}_BITS[] PROGMEM = {{" + ",".join(f"0x{b:02X}" for b in data) + "};")
        c_out.append(f"static const uint8_t {name}_ADV[] PROGMEM = {{" + ",".join(str(adv[c]) for c in range(FIRST, LAST + 1)) + "};")
        hrows = [y - top for y in range(top, top + h) if any(glyphs[ord("H")][y][:8])]
        cap_top, cap_h = hrows[0], hrows[-1] - hrows[0] + 1
        c_out.append(f"const PixelFont FONT_{name} = {{ {name}_BITS, {name}_ADV, {h}, {cap_top}, {cap_h} }};\n")
        h_out.append(f"extern const PixelFont FONT_{name};  // {h} px tall")
    open(os.path.join(ROOT, "src", "font_data.h"), "w").write("\n".join(h_out) + "\n")
    open(os.path.join(ROOT, "src", "font_data.cpp"), "w").write("\n".join(c_out) + "\n")
    print("ok")


if __name__ == "__main__":
    sys.exit(main())
